#!/usr/bin/env bash
# gen-env.sh — generate a HikRAD hikrad.env with fresh secrets (FR-49.1;
# reworked v4-2/FR-118 from a Docker Compose `.env` generator into the
# native systemd installer's `/etc/hikrad/hikrad.env` generator — same
# secrets, same idempotent-refusal contract, localhost service URLs instead
# of Compose service names).
#
# Usage: gen-env.sh [--env dev|prod] [--force] [OUTPUT_PATH]
#   OUTPUT_PATH defaults to <repo>/deploy/hikrad.env (dev); scripts/install.sh
#               always passes /etc/hikrad/hikrad.env explicitly.
#   --env       HIKRAD_ENV value (default: dev; scripts/install.sh passes prod)
#   --force     overwrite an existing file (default: refuse — this is what
#               makes install.sh's re-run idempotency guarantee hold: a
#               second install.sh run never calls this without --force, so
#               existing secrets are never regenerated, gate item 3)
#
# Env overrides (installer non-interactive contract, frozen — phase brief
# §3.1): HIKRAD_DB_PASS, if set, is used as the PostgreSQL role password
# verbatim instead of generating a random one (e.g. pointing at an
# already-provisioned managed Postgres, or a reproducible scripted install).
#
# Never prints secrets to stdout; the file is created mode 0600.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT=""
HIKRAD_ENV_VALUE="dev"
FORCE=0

while [ $# -gt 0 ]; do
    case "$1" in
        --env)
            HIKRAD_ENV_VALUE="${2:?--env requires dev|prod}"
            shift 2
            ;;
        --force)
            FORCE=1
            shift
            ;;
        -h|--help)
            sed -n '2,20p' "$0"
            exit 0
            ;;
        *)
            OUT="$1"
            shift
            ;;
    esac
done

case "$HIKRAD_ENV_VALUE" in
    dev|prod) ;;
    *) echo "error: --env must be dev or prod, got '$HIKRAD_ENV_VALUE'" >&2; exit 1 ;;
esac

[ -n "$OUT" ] || OUT="$SCRIPT_DIR/../deploy/hikrad.env"

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
    echo "error: $OUT already exists — refusing to overwrite secrets (use --force)" >&2
    exit 1
fi

command -v openssl >/dev/null 2>&1 || { echo "error: openssl is required" >&2; exit 1; }

# URL-safe (hex) DB password so HIKRAD_DB_URL needs no escaping. HIKRAD_DB_PASS
# (installer contract, frozen) lets a caller pin the password instead.
PG_PASSWORD="${HIKRAD_DB_PASS:-$(openssl rand -hex 24)}"
# 32 bytes base64 — AES-256-GCM key for subscriber password encryption (NFR-4.2).
ENCRYPTION_KEY="$(openssl rand -base64 32)"
JWT_SECRET="$(openssl rand -base64 48 | tr -d '\n')"
# Backup archive passphrase (FR-51.1) — install.sh prints this once to the
# install summary so the operator has an out-of-band copy; losing both that
# and this file's copy makes existing backups permanently unrecoverable by
# design (no vendor escrow) — see docs/ops/backup-restore.md.
BACKUP_PASSPHRASE="$(openssl rand -base64 24 | tr -d '\n')"
# Shared secret authenticating hikrad-api's socket calls to hikrad-updaterd
# (FR-86.2, retargeted onto systemd in v4-2/FR-121) — same generation recipe
# as HIKRAD_JWT_SECRET. Read by both sides from this one file: the daemon via
# its systemd EnvironmentFile, hikrad-api via its own. No separate
# provisioning step.
HIKRAD_UPDATER_TOKEN="$(openssl rand -base64 32 | tr -d '\n')"

umask 077
mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
# HikRAD environment — generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Contains secrets: keep mode 0600, never commit, include in backups (FR-51.1).
# Native install (v4-2): loaded by every hikrad-*.service unit's
# EnvironmentFile= (deploy/systemd/) — every service runs on this same host,
# so URLs below are localhost, not a Compose service name.

POSTGRES_USER=hikrad
POSTGRES_PASSWORD=${PG_PASSWORD}
POSTGRES_DB=hikrad

HIKRAD_DB_URL=postgres://hikrad:${PG_PASSWORD}@127.0.0.1:5432/hikrad?sslmode=disable
HIKRAD_REDIS_URL=redis://127.0.0.1:6379/0
HIKRAD_ENCRYPTION_KEY=${ENCRYPTION_KEY}
HIKRAD_JWT_SECRET=${JWT_SECRET}
HIKRAD_ENV=${HIKRAD_ENV_VALUE}

# Backup (FR-51): schedule/retention are Settings > Backups-configurable in
# the panel too; these are the values the hikrad CLI's backup command and the
# nightly systemd timer fall back to when unset there.
HIKRAD_BACKUP_PASSPHRASE=${BACKUP_PASSPHRASE}
HIKRAD_BACKUP_RETENTION=14

# One-click updater (FR-86, retargeted v4-2/FR-121): shared token between
# hikrad-updaterd (host daemon) and hikrad-api (relay). Never sent anywhere
# except the local unix socket between them.
HIKRAD_UPDATER_TOKEN=${HIKRAD_UPDATER_TOKEN}
EOF

echo "wrote $OUT (HIKRAD_ENV=${HIKRAD_ENV_VALUE})"
